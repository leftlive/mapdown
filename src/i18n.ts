let current: Record<StringKey, string> = en;

/** Pick the language from Obsidian's (`getLanguage()`); only "zh" switches to Chinese. */
export function setLanguage(lang: string): void {
	current = lang === 'zh' ? zh : en;
}

export function isChinese(): boolean {
	return current === zh;
}

export function t(key: StringKey, ...args: (string | number)[]): string {
	return (current[key] ?? en[key]).replace(/\{(\d)\}/g, (_, i: string) => String(args[Number(i)] ?? ''));
}
